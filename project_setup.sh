#Enviroment check
python_check () {
    if command -v python3 >/dev/null 2>&1 ; then
        echo "Python 3 is installed: $(python3 --version)"
    else
        echo "Python 3 is NOT installed." >&2
        echo " Install python : sudo apt update && sudo apt install -y python3" >&2
        exit 1
    fi
}


folder_check() {
    if [[ -e "$project_name" ]]; then
        echo "Error: '$project_name' already exists. Choose another name or remove it." >&2
        exit 1
    fi
}

folder_create (){
    python_check
    folder_check
    folder=$(mkdir $project_name)
    echo "Folder : ($project_name) succesfully created" 
}
folder_create

options_folder_select (){
    PARENT_DIR=$(cd "$project_name" && pwd)
    LOG_FILE="$PARENT_DIR/logs/setup.log"

    # ==============================================================================
    DIRS=(
        "$PARENT_DIR/data/raw"        # Original, untouched datasets (never edit directly)
        "$PARENT_DIR/data/processed"  # Cleaned and transformed data generated by scripts
        "$PARENT_DIR/src"             # Main reusable Python source code and modules
        "$PARENT_DIR/notebooks"       # Jupyter notebooks for exploration and experiments
        "$PARENT_DIR/tests"           # Automated unit and integration tests (e.g., pytest)
        "$PARENT_DIR/logs"            # Runtime and setup logs for tracking and debugging
        "$PARENT_DIR/config"          # Configuration files (.yaml, .json, .toml) and settings
    )

    # ==============================================================================
    # 📝 STARTER FILES (STARTER_FILES)
    # ==============================================================================
    STARTER_FILES=(
        "$PARENT_DIR/README.md"        # Project overview, folder guide, and setup instructions
        "$PARENT_DIR/requirements.txt" # Python dependencies list (pip install -r requirements.txt)
        "$PARENT_DIR/.gitignore"       # Files/folders Git should ignore (.venv, logs, raw data)
    )

    # Ensure the logs folder exists first so tee can write to it
    mkdir -p "$PARENT_DIR/logs"

   
   options=""
    
    while true ; do
        echo "=========================================="
        echo "🚀 Project Setup Menu ($PARENT_DIR)"
        echo "=========================================="
        echo "1) 📁 Create project directories"
        echo "2) 🐍 Install virtual environment (.venv)"
        echo "3) 📝 Create starter files"
        echo "4) 🚪 Exit"
        read -rp "👉 Choose an option [1-4]: " options || break

        case "$options" in 
                1)
                # Create all directories, prepend timestamps, show on terminal, and save to log
                echo "🏗️  BUILDING PROJECT DIRECTORIES ... 📂"
                mkdir -pv "${DIRS[@]}" 2>&1 | sed "s/^/[$(date '+%Y-%m-%d %H:%M:%S')] /" | tee -a "$LOG_FILE"
        
                ;;

                2)
                # Add VENV environment
                echo "🐍 INSTALLING VIRTUAL ENVIRONMENT ... 🛜"
                python3 -m venv "$PARENT_DIR/.venv" 2>&1  | tee -a "$LOG_FILE"
                echo "🚀 DONE INSTALLING .VENV! ✅"
            
                ;;

                3)
                echo "✍️  CREATING STARTER FILES ... 📄"
                touch "${STARTER_FILES[@]}" && printf "[$(date '+%Y-%m-%d %H:%M:%S')] touched '%s'\n" "${STARTER_FILES[@]}"
                echo "🎯 STARTER FILES CREATED! 🔥"
                ;;

                4)
                echo "👋 All done! Happy coding! 💻✨"
                exit 0
                ;;
                *)
                echo "❌ Invalid choice. Cancelled."
                exit 1
                ;;
            esac
    done
}

options_folder_select

